-- ============================================================================
--  Script 01: Criação do banco (DDL) — Oracle Database
--  Ordem de execução: 01 -> 02 -> 03

--  Parte 1: tabelas de cadastro
--  Parte 2: tabelas da Inteligência Artificial (Vigias B e C) e de referência
--  Parte 3: índices para as consultas dos vigias
-- ============================================================================
-- Desliga as variáveis de substituição (evita a janela "Substitutions")
SET DEFINE OFF;


-- ============================================================================
--  DROP das tabelas (bloco ignora o erro "tabela não existe").
-- ============================================================================
BEGIN
    FOR t IN (
        SELECT column_value AS nome FROM TABLE(sys.odcivarchar2list(
            'T_CLYVO_ALERTA',
            'T_CLYVO_LEITURA_SENSOR',
            'T_CLYVO_REF_RACAO',
            'T_CLYVO_REF_CONSUMO',
            'T_CLYVO_VACINA_DOENCA',
            'T_CLYVO_PREDISP_RACA',
            'T_CLYVO_PREDISP_ESPECIE',
            'T_CLYVO_REF_PESO_RACA',
            'T_CLYVO_CONSULTA_DOENCA',
            'T_CLYVO_DOENCA',
            'T_CLYVO_MEDICAMENTO',
            'T_CLYVO_PRESCRICAO',
            'T_CLYVO_CONSULTA',
            'T_CLYVO_VACINACAO',
            'T_CLYVO_VACINA',
            'T_CLYVO_ENDERECO_ANIMAL',
            'T_CLYVO_ANIMAL',
            'T_CLYVO_ESPECIE',
            'T_CLYVO_ENDERECO_CLINICA',
            'T_CLYVO_ENDERECO_RESPONSAVEL',
            'T_CLYVO_CLINICA_VET',
            'T_CLYVO_CLINICA',
            'T_CLYVO_VET',
            'T_CLYVO_RESPONSAVEL'
        ))
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || t.nome || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN RAISE; END IF;
        END;
    END LOOP;
END;
/


-- ============================================================================
--  PARTE 1 — TABELAS DE CADASTRO
