-- ----------------------------------------------------------------------------
-- Catálogo de doenças (seções 12.3 e 12.4 do README; planilhas
-- catalogo_doencas.csv e ref_doencas.csv)
--   tp_doenca         : INFECCIOSA ou CRONICA
--   especie_alvo      : espécie afetada (correlação 13). Doenças que atingem
--                       mais de uma espécie (raiva) têm uma linha por espécie.
--   contagiosa        : passa de um animal para outro (correlação 14)
--   zoonose           : passa para humanos
--   monitora_surto    : S = o Vigia C procura surtos desta doença
--   alerta_caso_unico : S = um único caso suspeito já gera alerta (raiva)
--   mes_inicio_pico / mes_fim_pico : época de pico (correlação 12); pode
--                       "virar o ano" (ex: 10 a 3)
--   idade_risco_anos  : idade em que a doença passa a ser comum (correlação 6)
--   sinal_comida / sinal_agua / sinal_movimento : efeito no sensor
--                       (1 = aumenta, -1 = diminui, 0 = sem efeito) — correlação 7
--   momento_sinal     : INICIAL ou TARDIO (sinal só em fase avançada)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_DOENCA (
    id_doenca          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_doenca          VARCHAR2(100) NOT NULL,
    especie_alvo       VARCHAR2(50)  NOT NULL,
    tp_doenca          VARCHAR2(20)  NOT NULL,
    contagiosa         CHAR(1)       DEFAULT 'N' NOT NULL,
    zoonose            CHAR(1)       DEFAULT 'N' NOT NULL,
    monitora_surto     CHAR(1)       DEFAULT 'N' NOT NULL,
    alerta_caso_unico  CHAR(1)       DEFAULT 'N' NOT NULL,
    mes_inicio_pico    NUMBER(2),
    mes_fim_pico       NUMBER(2),
    idade_risco_anos   NUMBER(4,1),
    sinal_comida       NUMBER(1)     DEFAULT 0 NOT NULL,
    sinal_agua         NUMBER(1)     DEFAULT 0 NOT NULL,
    sinal_movimento    NUMBER(1)     DEFAULT 0 NOT NULL,
    momento_sinal      VARCHAR2(10),
    ds_transmissao     VARCHAR2(300),
    ds_prevencao       VARCHAR2(300),
    ds_sinais_clinicos VARCHAR2(300),
    ds_dados_brasil    VARCHAR2(400),
    ds_fonte           VARCHAR2(500) NOT NULL,
    ds_link            VARCHAR2(300),
    CONSTRAINT pk_doenca             PRIMARY KEY (id_doenca),
    CONSTRAINT uq_doenca_nome        UNIQUE (nm_doenca, especie_alvo),
    CONSTRAINT ck_doenca_tipo        CHECK (tp_doenca IN ('INFECCIOSA', 'CRONICA')),
    CONSTRAINT ck_doenca_contagiosa  CHECK (contagiosa IN ('S', 'N')),
    CONSTRAINT ck_doenca_zoonose     CHECK (zoonose IN ('S', 'N')),
    CONSTRAINT ck_doenca_monitora    CHECK (monitora_surto IN ('S', 'N')),
    CONSTRAINT ck_doenca_caso_unico  CHECK (alerta_caso_unico IN ('S', 'N')),
    CONSTRAINT ck_doenca_mes_ini     CHECK (mes_inicio_pico IS NULL OR mes_inicio_pico BETWEEN 1 AND 12),
    CONSTRAINT ck_doenca_mes_fim     CHECK (mes_fim_pico    IS NULL OR mes_fim_pico    BETWEEN 1 AND 12),
    CONSTRAINT ck_doenca_idade       CHECK (idade_risco_anos IS NULL OR idade_risco_anos >= 0),
    CONSTRAINT ck_doenca_sinal_com   CHECK (sinal_comida    IN (-1, 0, 1)),
    CONSTRAINT ck_doenca_sinal_agua  CHECK (sinal_agua      IN (-1, 0, 1)),
    CONSTRAINT ck_doenca_sinal_mov   CHECK (sinal_movimento IN (-1, 0, 1)),
    CONSTRAINT ck_doenca_momento     CHECK (momento_sinal IS NULL OR momento_sinal IN ('INICIAL', 'TARDIO')),
    CONSTRAINT fk_doenca_especie     FOREIGN KEY (especie_alvo) REFERENCES T_CLYVO_ESPECIE (nm_especie)
);

-- ----------------------------------------------------------------------------
-- Diagnósticos registrados em cada consulta (Vigia C — correlação 11)
-- Ligada ao animal pela consulta e, pelo animal, ao bairro.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_CONSULTA_DOENCA (
    id_consulta_doenca NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_consulta        NUMBER(19) NOT NULL,
    id_doenca          NUMBER(19) NOT NULL,
    CONSTRAINT pk_consulta_doenca     PRIMARY KEY (id_consulta_doenca),
    CONSTRAINT uq_consulta_doenca     UNIQUE (id_consulta, id_doenca),
    CONSTRAINT fk_cons_doenca_consulta FOREIGN KEY (id_consulta) REFERENCES T_CLYVO_CONSULTA (id_consulta),
    CONSTRAINT fk_cons_doenca_doenca   FOREIGN KEY (id_doenca)   REFERENCES T_CLYVO_DOENCA (id_doenca)
);

-- ----------------------------------------------------------------------------
-- Vacina x doença que ela previne (correlação 8 e ligação entre os vigias)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_VACINA_DOENCA (
    id_vacina_doenca NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_vacina        NUMBER(19)   NOT NULL,
    id_doenca        NUMBER(19)   NOT NULL,
    ds_cobertura     VARCHAR2(80) NOT NULL,
    CONSTRAINT pk_vacina_doenca        PRIMARY KEY (id_vacina_doenca),
    CONSTRAINT uq_vacina_doenca        UNIQUE (id_vacina, id_doenca),
    CONSTRAINT fk_vacina_doenca_vacina FOREIGN KEY (id_vacina) REFERENCES T_CLYVO_VACINA (id_vacina),
    CONSTRAINT fk_vacina_doenca_doenca FOREIGN KEY (id_doenca) REFERENCES T_CLYVO_DOENCA (id_doenca)
);

-- ----------------------------------------------------------------------------
-- Peso ideal de adultos por espécie, raça e sexo (seção 12.1; ref_peso.csv)
--   sexo_animal: M, F ou A (Ambos — a fonte não separa por sexo)
--   media_kg / desvio_kg / n_animais: preenchidos quando a fonte é um estudo
-- Correlações 1, 2, 4 e 10 do Vigia B.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_REF_PESO_RACA (
    id_ref_peso    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    especie_animal VARCHAR2(50)  NOT NULL,
    raca_animal    VARCHAR2(50)  NOT NULL,
    raca_original  VARCHAR2(60),
    sexo_animal    CHAR(1)       NOT NULL,
    peso_min_kg    NUMBER(6,2)   NOT NULL,
    peso_max_kg    NUMBER(6,2)   NOT NULL,
    media_kg       NUMBER(6,2),
    desvio_kg      NUMBER(6,2),
    n_animais      NUMBER(6),
    ds_fonte       VARCHAR2(300) NOT NULL,
    CONSTRAINT pk_ref_peso_raca    PRIMARY KEY (id_ref_peso),
    CONSTRAINT uq_ref_peso_raca    UNIQUE (especie_animal, raca_animal, sexo_animal),
    CONSTRAINT ck_ref_peso_sexo    CHECK (sexo_animal IN ('M', 'F', 'A')),
    CONSTRAINT ck_ref_peso_faixa   CHECK (peso_min_kg > 0 AND peso_max_kg > peso_min_kg),
    CONSTRAINT fk_ref_peso_especie FOREIGN KEY (especie_animal) REFERENCES T_CLYVO_ESPECIE (nm_especie)
);

-- ----------------------------------------------------------------------------
-- Predisposições e proteções por raça (seção 12.2; ref_predisposicao.csv)
--   tp_relacao     : PREDISPOSICAO (mais chance) ou PROTECAO (menos chance)
--   vl_razao_risco : quantas vezes mais (ou menos) chance; vazio quando a
--                    evidência é uma mutação genética da raça
-- Correlações 6 e 7 do Vigia B.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_PREDISP_RACA (
    id_predisp_raca NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    especie_animal  VARCHAR2(50)  NOT NULL,
    raca_animal     VARCHAR2(50)  NOT NULL,
    id_doenca       NUMBER(19)    NOT NULL,
    tp_relacao      VARCHAR2(15)  NOT NULL,
    vl_razao_risco  NUMBER(6,2),
    ds_medida       VARCHAR2(60),
    ds_observacao   VARCHAR2(500),
    ds_fonte        VARCHAR2(300) NOT NULL,
    ds_link         VARCHAR2(300),
    CONSTRAINT pk_predisp_raca         PRIMARY KEY (id_predisp_raca),
    CONSTRAINT uq_predisp_raca         UNIQUE (especie_animal, raca_animal, id_doenca),
    CONSTRAINT ck_predisp_raca_relacao CHECK (tp_relacao IN ('PREDISPOSICAO', 'PROTECAO')),
    CONSTRAINT ck_predisp_raca_razao   CHECK (vl_razao_risco IS NULL OR vl_razao_risco > 0),
    CONSTRAINT fk_predisp_raca_especie FOREIGN KEY (especie_animal) REFERENCES T_CLYVO_ESPECIE (nm_especie),
    CONSTRAINT fk_predisp_raca_doenca  FOREIGN KEY (id_doenca) REFERENCES T_CLYVO_DOENCA (id_doenca)
);

-- ----------------------------------------------------------------------------
-- Fórmulas de consumo esperado (seção 12.7; ref_consumo.csv)
--   comida (kcal/dia) = coef_rer x peso^expoente x fator_manutencao
--   água   (ml/dia)   = coef_agua_ml x peso^expoente
--   tolerancia        : variação individual aceita (0,30 = 30%)
-- Correlações 2 e 4 do Vigia B.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_REF_CONSUMO (
    id_ref_consumo   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    especie_animal   VARCHAR2(50)  NOT NULL,
    castrado         CHAR(1)       NOT NULL,
    coef_rer         NUMBER(6,2)   NOT NULL,
    expoente         NUMBER(4,3)   NOT NULL,
    fator_manutencao NUMBER(4,2)   NOT NULL,
    coef_agua_ml     NUMBER(6,2)   NOT NULL,
    tolerancia       NUMBER(4,2)   NOT NULL,
    ds_fonte         VARCHAR2(500) NOT NULL,
    CONSTRAINT pk_ref_consumo         PRIMARY KEY (id_ref_consumo),
    CONSTRAINT uq_ref_consumo         UNIQUE (especie_animal, castrado),
    CONSTRAINT ck_ref_consumo_castr   CHECK (castrado IN ('S', 'N')),
    CONSTRAINT fk_ref_consumo_especie FOREIGN KEY (especie_animal) REFERENCES T_CLYVO_ESPECIE (nm_especie)
);

-- ----------------------------------------------------------------------------
-- Rações de referência (seção 12.7; ref_racoes.csv)
-- Energia publicada pelos fabricantes. A média por espécie é usada quando o
-- animal não tem kcal_kg_racao informado.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_REF_RACAO (
    id_ref_racao    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    especie_animal  VARCHAR2(50)  NOT NULL,
    nm_produto      VARCHAR2(100) NOT NULL,
    nm_fabricante   VARCHAR2(60)  NOT NULL,
    para_castrados  CHAR(1)       NOT NULL,
    kcal_kg         NUMBER(6)     NOT NULL,
    umidade_max_pct NUMBER(4,1),
    ds_link         VARCHAR2(300) NOT NULL,
    CONSTRAINT pk_ref_racao         PRIMARY KEY (id_ref_racao),
    CONSTRAINT uq_ref_racao         UNIQUE (nm_produto),
    CONSTRAINT ck_ref_racao_castr   CHECK (para_castrados IN ('S', 'N')),
    CONSTRAINT ck_ref_racao_kcal    CHECK (kcal_kg > 0),
    CONSTRAINT fk_ref_racao_especie FOREIGN KEY (especie_animal) REFERENCES T_CLYVO_ESPECIE (nm_especie)
);

-- ----------------------------------------------------------------------------
-- Leituras dos sensores (Vigia B — correlações 2, 3 e 5)
-- Mesmos dados que o ESP32 envia ao Thinger.io, já convertidos pelo servidor:
--   consumo_comida_g  : consumo de ração no período (balança HX711)
--   consumo_agua_ml   : consumo de água no período (balança HX711)
--   nivel_movimento   : intensidade de movimento de 0 a 100 (MPU6050)
--   id_dispositivo    : DEVICE_ID do ESP32 vinculado ao animal
-- Nesta entrega, as leituras são SIMULADAS no mesmo formato do dispositivo.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_LEITURA_SENSOR (
    id_leitura       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_animal        NUMBER(19)   NOT NULL,
    dt_leitura       TIMESTAMP    NOT NULL,
    consumo_comida_g NUMBER(8,2)  NOT NULL,
    consumo_agua_ml  NUMBER(8,2)  NOT NULL,
    nivel_movimento  NUMBER(5,2)  NOT NULL,
    id_dispositivo   VARCHAR2(50),
    CONSTRAINT pk_leitura_sensor PRIMARY KEY (id_leitura),
    CONSTRAINT ck_leitura_comida CHECK (consumo_comida_g >= 0),
    CONSTRAINT ck_leitura_agua   CHECK (consumo_agua_ml  >= 0),
    CONSTRAINT ck_leitura_mov    CHECK (nivel_movimento BETWEEN 0 AND 100),
    CONSTRAINT fk_leitura_animal FOREIGN KEY (id_animal) REFERENCES T_CLYVO_ANIMAL (id_animal)
);

-- ----------------------------------------------------------------------------
-- Alertas gerados pelos vigias
--   tp_alerta    : INDIVIDUAL (Vigia B), ROTINA (check-up, correlação 9)
--                  ou REGIONAL (Vigia C)
--   vigia_origem : A, B ou C
--   nivel_risco  : BAIXO / MEDIO / ALTO
--   probabilidade: confiança do modelo na classificação (0 a 1)
--   ds_motivo    : explicação do alerta ("por que você recebeu este alerta")
--   st_notificacao: envio ao tutor (WhatsApp simulado nesta entrega)
-- Alerta individual/rotina exige animal; alerta regional exige bairro e doença.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ALERTA (
    id_alerta        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tp_alerta        VARCHAR2(20)  NOT NULL,
    vigia_origem     CHAR(1)       NOT NULL,
    nivel_risco      VARCHAR2(10)  NOT NULL,
    probabilidade    NUMBER(5,4),
    ds_motivo        VARCHAR2(500) NOT NULL,
    ds_recomendacao  VARCHAR2(300),
    dt_alerta        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    st_alerta        VARCHAR2(20)  DEFAULT 'ATIVO' NOT NULL,
    st_notificacao   VARCHAR2(20)  DEFAULT 'PENDENTE' NOT NULL,
    id_animal        NUMBER(19),
    cidade           VARCHAR2(20),
    bairro           VARCHAR2(20),
    id_doenca        NUMBER(19),
    CONSTRAINT pk_alerta              PRIMARY KEY (id_alerta),
    CONSTRAINT ck_alerta_tipo         CHECK (tp_alerta IN ('INDIVIDUAL', 'ROTINA', 'REGIONAL')),
    CONSTRAINT ck_alerta_vigia        CHECK (vigia_origem IN ('A', 'B', 'C')),
    CONSTRAINT ck_alerta_nivel        CHECK (nivel_risco IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT ck_alerta_prob         CHECK (probabilidade IS NULL OR probabilidade BETWEEN 0 AND 1),
    CONSTRAINT ck_alerta_status       CHECK (st_alerta IN ('ATIVO', 'RESOLVIDO')),
    CONSTRAINT ck_alerta_notificacao  CHECK (st_notificacao IN ('PENDENTE', 'SIMULADO', 'ENVIADO')),
    CONSTRAINT ck_alerta_alvo         CHECK (
        (tp_alerta IN ('INDIVIDUAL', 'ROTINA') AND id_animal IS NOT NULL)
        OR
        (tp_alerta = 'REGIONAL' AND bairro IS NOT NULL AND id_doenca IS NOT NULL)
    ),
    CONSTRAINT fk_alerta_animal FOREIGN KEY (id_animal) REFERENCES T_CLYVO_ANIMAL (id_animal),
    CONSTRAINT fk_alerta_doenca FOREIGN KEY (id_doenca) REFERENCES T_CLYVO_DOENCA (id_doenca)
);


-- ============================================================================
