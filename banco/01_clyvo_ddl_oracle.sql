-- ----------------------------------------------------------------------------
-- Responsável (tutor) do animal. Recebe os alertas via WhatsApp.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_RESPONSAVEL (
    id_responsavel          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_responsavel          VARCHAR2(100) NOT NULL,
    cpf_responsavel         VARCHAR2(14)  NOT NULL,
    nr_telefone_responsavel VARCHAR2(20)  NOT NULL,
    ds_email                VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_responsavel     PRIMARY KEY (id_responsavel),
    CONSTRAINT uq_responsavel_cpf UNIQUE (cpf_responsavel)
);

-- ----------------------------------------------------------------------------
-- Veterinário
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_VET (
    id_vet   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_vet   VARCHAR2(100) NOT NULL,
    cpf_vet  VARCHAR2(14)  NOT NULL,
    crmv_vet VARCHAR2(20)  NOT NULL,
    email    VARCHAR2(100) NOT NULL,
    senha    VARCHAR2(255) NOT NULL,
    CONSTRAINT pk_vet       PRIMARY KEY (id_vet),
    CONSTRAINT uq_vet_cpf   UNIQUE (cpf_vet),
    CONSTRAINT uq_vet_crmv  UNIQUE (crmv_vet),
    CONSTRAINT uq_vet_email UNIQUE (email)
);

-- ----------------------------------------------------------------------------
-- Clínica parceira. Os diagnósticos das clínicas alimentam o Vigia C.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_CLINICA (
    id_clinica   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cnpj_clinica VARCHAR2(20)  NOT NULL,
    nm_clinica   VARCHAR2(100) NOT NULL,
    email        VARCHAR2(100) NOT NULL,
    senha        VARCHAR2(255) NOT NULL,
    st_contrato  VARCHAR2(20)  DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT pk_clinica        PRIMARY KEY (id_clinica),
    CONSTRAINT uq_clinica_cnpj   UNIQUE (cnpj_clinica),
    CONSTRAINT uq_clinica_email  UNIQUE (email),
    CONSTRAINT ck_clinica_status CHECK (st_contrato IN ('ATIVO', 'INATIVO'))
);

-- ----------------------------------------------------------------------------
-- Vínculo N:N entre clínica e veterinário (a consulta aponta para este vínculo).
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_CLINICA_VET (
    id_clinica_vet NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_clinica     NUMBER(19) NOT NULL,
    id_veterinario NUMBER(19) NOT NULL,
    CONSTRAINT pk_clinica_vet         PRIMARY KEY (id_clinica_vet),
    CONSTRAINT uq_clinica_vet         UNIQUE (id_clinica, id_veterinario),
    CONSTRAINT fk_clinica_vet_clinica FOREIGN KEY (id_clinica)     REFERENCES T_CLYVO_CLINICA (id_clinica),
    CONSTRAINT fk_clinica_vet_vet     FOREIGN KEY (id_veterinario) REFERENCES T_CLYVO_VET (id_vet)
);

-- ----------------------------------------------------------------------------
-- Endereço do responsável (1:1)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ENDERECO_RESPONSAVEL (
    id             NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pais           VARCHAR2(20) NOT NULL,
    estado         VARCHAR2(20) NOT NULL,
    cidade         VARCHAR2(20) NOT NULL,
    bairro         VARCHAR2(20) NOT NULL,
    logradouro     VARCHAR2(50) NOT NULL,
    nr_rua         VARCHAR2(15) NOT NULL,
    complemento    VARCHAR2(20),
    cep            VARCHAR2(9)  NOT NULL,
    id_responsavel NUMBER(19)   NOT NULL,
    CONSTRAINT pk_end_responsavel    PRIMARY KEY (id),
    CONSTRAINT uq_end_responsavel    UNIQUE (id_responsavel),
    CONSTRAINT fk_end_responsavel    FOREIGN KEY (id_responsavel) REFERENCES T_CLYVO_RESPONSAVEL (id_responsavel)
);

-- ----------------------------------------------------------------------------
-- Endereço da clínica (1:N — uma clínica pode ter filiais)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ENDERECO_CLINICA (
    id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pais        VARCHAR2(20) NOT NULL,
    estado      VARCHAR2(20) NOT NULL,
    cidade      VARCHAR2(20) NOT NULL,
    bairro      VARCHAR2(20) NOT NULL,
    logradouro  VARCHAR2(50) NOT NULL,
    nr_rua      VARCHAR2(15) NOT NULL,
    complemento VARCHAR2(20),
    cep         VARCHAR2(9)  NOT NULL,
    id_clinica  NUMBER(19)   NOT NULL,
    CONSTRAINT pk_end_clinica PRIMARY KEY (id),
    CONSTRAINT fk_end_clinica FOREIGN KEY (id_clinica) REFERENCES T_CLYVO_CLINICA (id_clinica)
);

-- ----------------------------------------------------------------------------
-- Espécies atendidas. Todas as colunas de espécie apontam para esta
-- tabela: evita grafias diferentes ("Canina", "canina", "Cão") e permite
-- incluir uma espécie nova (ex: Equina) inserindo apenas uma linha.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ESPECIE (
    id_especie NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_especie VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_especie      PRIMARY KEY (id_especie),
    CONSTRAINT uq_especie_nome UNIQUE (nm_especie)
);

-- ----------------------------------------------------------------------------
-- Animal (paciente)
--   castrado      : S/N (correlações 2 e 10 do Vigia B)
--   sexo_animal   : M/F (faixa de peso dos gatos é separada por sexo)
--   kcal_kg_racao : energia da ração informada no rótulo (correlação 2);
--                   pode ficar vazia — o sistema usa a média das rações de referência
--   especie_animal: continua texto (compatível com o projeto Java), mas validada
--                   pela tabela de espécies
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ANIMAL (
    id_animal            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_animal            VARCHAR2(100) NOT NULL,
    dt_nascimento_animal DATE          NOT NULL,
    peso_animal          NUMBER(5,2)   NOT NULL,
    especie_animal       VARCHAR2(50)  NOT NULL,
    raca_animal          VARCHAR2(50)  NOT NULL,
    sexo_animal          CHAR(1)       NOT NULL,
    castrado             CHAR(1)       DEFAULT 'N' NOT NULL,
    kcal_kg_racao        NUMBER(6),
    rg_animal            VARCHAR2(20),
    nr_microchip_animal  VARCHAR2(20),
    id_responsavel       NUMBER(19)    NOT NULL,
    CONSTRAINT pk_animal             PRIMARY KEY (id_animal),
    CONSTRAINT uq_animal_rg          UNIQUE (rg_animal),
    CONSTRAINT uq_animal_microchip   UNIQUE (nr_microchip_animal),
    CONSTRAINT ck_animal_peso        CHECK (peso_animal > 0),
    CONSTRAINT ck_animal_sexo        CHECK (sexo_animal IN ('M', 'F')),
    CONSTRAINT ck_animal_castrado    CHECK (castrado IN ('S', 'N')),
    CONSTRAINT ck_animal_kcal        CHECK (kcal_kg_racao IS NULL OR kcal_kg_racao > 0),
    CONSTRAINT fk_animal_especie     FOREIGN KEY (especie_animal) REFERENCES T_CLYVO_ESPECIE (nm_especie),
    CONSTRAINT fk_animal_responsavel FOREIGN KEY (id_responsavel) REFERENCES T_CLYVO_RESPONSAVEL (id_responsavel)
);

-- ----------------------------------------------------------------------------
-- Endereço do animal (1:1). O BAIRRO é a base geográfica do Vigia C.
-- Pode ser diferente do endereço do responsável.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_ENDERECO_ANIMAL (
    id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pais        VARCHAR2(20) NOT NULL,
    estado      VARCHAR2(20) NOT NULL,
    cidade      VARCHAR2(20) NOT NULL,
    bairro      VARCHAR2(20) NOT NULL,
    logradouro  VARCHAR2(50) NOT NULL,
    nr_rua      VARCHAR2(15) NOT NULL,
    complemento VARCHAR2(20),
    cep         VARCHAR2(9)  NOT NULL,
    id_animal   NUMBER(19)   NOT NULL,
    CONSTRAINT pk_end_animal PRIMARY KEY (id),
    CONSTRAINT uq_end_animal UNIQUE (id_animal),
    CONSTRAINT fk_end_animal FOREIGN KEY (id_animal) REFERENCES T_CLYVO_ANIMAL (id_animal)
);

-- ----------------------------------------------------------------------------
-- Vacinas (referência — seção 12.5 do README)
--   qt_reforco_meses : intervalo de reforço; acima disso a vacina está atrasada
--   As doenças que cada vacina previne ficam em T_CLYVO_VACINA_DOENCA.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_VACINA (
    id_vacina        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_vacina        VARCHAR2(40)  NOT NULL,
    ds_composicao    VARCHAR2(200),
    qt_reforco_meses NUMBER(3)     NOT NULL,
    ds_classificacao VARCHAR2(40),
    ds_fonte         VARCHAR2(500) NOT NULL,
    ds_link          VARCHAR2(300),
    CONSTRAINT pk_vacina         PRIMARY KEY (id_vacina),
    CONSTRAINT uq_vacina_nome    UNIQUE (nm_vacina),
    CONSTRAINT ck_vacina_reforco CHECK (qt_reforco_meses > 0)
);

-- ----------------------------------------------------------------------------
-- Vacinação (correlação 8 do Vigia B)
-- nm_vacina continua texto, validado pela tabela de vacinas.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_VACINACAO (
    id_vacinacao          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_vacina             VARCHAR2(40) NOT NULL,
    dt_vacinacao_prevista DATE         NOT NULL,
    dt_vacinacao_efetuada DATE,
    st_vacinacao          VARCHAR2(20) NOT NULL,
    id_animal             NUMBER(19)   NOT NULL,
    CONSTRAINT pk_vacinacao        PRIMARY KEY (id_vacinacao),
    CONSTRAINT ck_vacinacao_status CHECK (st_vacinacao IN ('EFETUADA', 'PENDENTE', 'ATRASADA', 'CANCELADA')),
    CONSTRAINT ck_vacinacao_data   CHECK (st_vacinacao <> 'EFETUADA' OR dt_vacinacao_efetuada IS NOT NULL),
    CONSTRAINT fk_vacinacao_vacina FOREIGN KEY (nm_vacina) REFERENCES T_CLYVO_VACINA (nm_vacina),
    CONSTRAINT fk_vacinacao_animal FOREIGN KEY (id_animal) REFERENCES T_CLYVO_ANIMAL (id_animal)
);

-- ----------------------------------------------------------------------------
-- Consulta (correlação 9 do Vigia B usa a data da consulta mais recente)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_CONSULTA (
    id_consulta        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    historico_consulta VARCHAR2(200) NOT NULL,
    st_consulta        VARCHAR2(20)  NOT NULL,
    dt_consulta        DATE          NOT NULL,
    id_vet_cli         NUMBER(19)    NOT NULL,
    id_animal          NUMBER(19)    NOT NULL,
    CONSTRAINT pk_consulta         PRIMARY KEY (id_consulta),
    CONSTRAINT ck_consulta_status  CHECK (st_consulta IN ('PASSADA', 'EM_ANDAMENTO', 'FUTURA', 'CANCELADA')),
    CONSTRAINT fk_consulta_vet_cli FOREIGN KEY (id_vet_cli) REFERENCES T_CLYVO_CLINICA_VET (id_clinica_vet),
    CONSTRAINT fk_consulta_animal  FOREIGN KEY (id_animal)  REFERENCES T_CLYVO_ANIMAL (id_animal)
);

-- ----------------------------------------------------------------------------
-- Prescrição (1:1 com consulta)
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_PRESCRICAO (
    id_prescricao      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    dt_emissao         DATE       NOT NULL,
    dt_expiracao       DATE       NOT NULL,
    observacoes_gerais VARCHAR2(255),
    id_consulta        NUMBER(19) NOT NULL,
    CONSTRAINT pk_prescricao          PRIMARY KEY (id_prescricao),
    CONSTRAINT uq_prescricao_consulta UNIQUE (id_consulta),
    CONSTRAINT ck_prescricao_datas    CHECK (dt_expiracao >= dt_emissao),
    CONSTRAINT fk_prescricao_consulta FOREIGN KEY (id_consulta) REFERENCES T_CLYVO_CONSULTA (id_consulta)
);

-- ----------------------------------------------------------------------------
-- Medicamento (N:1 com prescrição)
-- Não usada pela IA. Possível aprimoramento futuro: cruzar medicação com os sinais do sensor.
-- ----------------------------------------------------------------------------
CREATE TABLE T_CLYVO_MEDICAMENTO (
    id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_medicamento     VARCHAR2(100) NOT NULL,
    qt_medicamento     NUMBER(10)    NOT NULL,
    qt_dias            NUMBER(10)    NOT NULL,
    vl_dose            NUMBER(5,2)   NOT NULL,
    un_dose            VARCHAR2(20)  NOT NULL,
    qt_frequencia      NUMBER(10)    NOT NULL,
    un_frequencia      VARCHAR2(20)  NOT NULL,
    forma_farmaceutica VARCHAR2(20)  NOT NULL,
    id_prescricao      NUMBER(19)    NOT NULL,
    CONSTRAINT pk_medicamento            PRIMARY KEY (id),
    CONSTRAINT ck_medicamento_qt         CHECK (qt_medicamento >= 1),
    CONSTRAINT ck_medicamento_dias       CHECK (qt_dias >= 1),
    CONSTRAINT ck_medicamento_freq       CHECK (qt_frequencia >= 1),
    CONSTRAINT ck_medicamento_forma      CHECK (forma_farmaceutica IN ('SOLIDA', 'SEMI_SOLIDA', 'LIQUIDA')),
    CONSTRAINT fk_medicamento_prescricao FOREIGN KEY (id_prescricao) REFERENCES T_CLYVO_PRESCRICAO (id_prescricao)
);


